#!/bin/bash
# Release packaging path (Developer ID signing, Hardened Runtime, notarization,
# stapling). FAIL-CLOSED: without a configured signing identity and notarytool
# profile this script exits without producing anything release-like — the only
# artifacts that exist without credentials are the dev/beta builds, which are
# marked dev-adhoc / beta-adhoc and must not be distributed.
#
# Not executed so far: no Developer ID identity and no notarization
# credentials are configured on the build machine. See
# docs/release-checklist.md for the open release gates.
#
# Required environment:
#   MACOS_SIGNING_IDENTITY         "Developer ID Application: <name> (TEAMID)"
#   NOTARYTOOL_KEYCHAIN_PROFILE    keychain profile created via
#                                  `xcrun notarytool store-credentials`
#
# Usage: scripts/release-package.sh
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
APP_BUNDLE="$ROOT/dist/Portname.app"
ZIP="$ROOT/dist/Portname-macos.zip"

err_not_released() {
  echo "NOT RELEASED: $*" >&2
  echo "No release artifact was produced. Ad-hoc/beta builds stay marked and undistributable." >&2
  exit 1
}

[ "$(uname)" = "Darwin" ] || err_not_released "release packaging runs on macOS only."
ARCH="$(uname -m)"
[ "$ARCH" = "arm64" ] || err_not_released "only arm64 is built and tested."

[ -n "${MACOS_SIGNING_IDENTITY:-}" ] || err_not_released "MACOS_SIGNING_IDENTITY is not configured (Developer ID Application certificate required)."
[ -n "${NOTARYTOOL_KEYCHAIN_PROFILE:-}" ] || err_not_released "NOTARYTOOL_KEYCHAIN_PROFILE is not configured (xcrun notarytool store-credentials)."

# A distributable zip from an earlier run must not outlive a failure of this
# one: next to a freshly rebuilt (or rejected) bundle it would pass for this
# run's release artifact.
rm -f "$ZIP"

echo "==> Building self-contained beta bundle (runtime procurement + manifest)"
# PORTNAME_RELEASE_PREBUILT=1 skips the bundle build and requires an existing
# dist/Portname.app (used for re-notarizing an already-built bundle and by the
# release-path regression test, which stubs the signing/notarization tools).
# Exact match on "1": any other value — including 0 or false —
# must run the build instead of silently reusing a stale dist/Portname.app.
# Either way the payload passes the pre-sign gate below.
if [ "${PORTNAME_RELEASE_PREBUILT:-}" = "1" ]; then
  [ -d "$APP_BUNDLE" ] || err_not_released "PORTNAME_RELEASE_PREBUILT is set but $APP_BUNDLE does not exist; build it with scripts/bundle-macos.sh first."
else
  "$SCRIPT_DIR/bundle-macos.sh"
fi

# The GUI's localization tables must be inside the app before anything is
# signed (also for a PREBUILT bundle from an older build script): only the
# build machine has the SwiftPM build-path fallback.
L10N_BUNDLE="$APP_BUNDLE/Contents/Resources/portname-macos_PortnameCore.bundle"
for lang in de en; do
  [ -f "$L10N_BUNDLE/$lang.lproj/Localizable.strings" ] \
    || [ -f "$L10N_BUNDLE/Contents/Resources/$lang.lproj/Localizable.strings" ] \
    || err_not_released "$lang Localizable.strings missing from $L10N_BUNDLE; rebuild with scripts/bundle-macos.sh."
done

RES="$APP_BUNDLE/Contents/Resources"

echo "==> Verifying the payload against its manifest and the runtime pins (before signing)"
# The manifest regeneration after signing refreshes only the re-signed
# runtime binaries; this gate makes sure what gets signed is the payload
# bundle-macos.sh built under the current scripts/runtime-pin.env — nothing
# edited, added or swapped since, no superseded runtime.
PRIOR_CHANNEL="$(plutil -extract PortnameBuildChannel raw "$APP_BUNDLE/Contents/Info.plist" 2>/dev/null || true)"
node "$SCRIPT_DIR/lib/release-preflight.js" "$RES" "$SCRIPT_DIR/runtime-pin.env" "$PRIOR_CHANNEL" \
  || err_not_released "the bundle payload does not match its manifest or the current runtime pins; rebuild it with scripts/bundle-macos.sh."

echo "==> Setting release channel marker before signing"
plutil -replace PortnameBuildChannel -string "release" "$APP_BUNDLE/Contents/Info.plist"

echo "==> Signing every Mach-O with Hardened Runtime + timestamp"
# ORDER MATTERS: codesigning rewrites the Mach-O bytes
# (embedded signature), so the payload manifest generated by bundle-macos.sh
# over the unsigned payload carries stale SHA-256s afterwards and `install`
# would deterministically fail closed on the target machine. Sequence:
#   1. sign the runtime binaries (node, cloudflared)
#   2. REGENERATE the payload manifest over the signed bytes
#   3. sign the GUI binary and the bundle (their seal must cover the fresh
#      manifest) → verify → notarize → staple
# Inner binaries first, then the GUI binary, then the bundle itself.
codesign --force --timestamp --options runtime \
  --entitlements "$SCRIPT_DIR/release/entitlements-node.plist" \
  --sign "$MACOS_SIGNING_IDENTITY" "$RES/runtime/bin/node"
if [ -f "$RES/runtime/bin/cloudflared" ]; then
  codesign --force --timestamp --options runtime \
    --entitlements "$SCRIPT_DIR/release/entitlements-cloudflared.plist" \
    --sign "$MACOS_SIGNING_IDENTITY" "$RES/runtime/bin/cloudflared"
fi

echo "==> Regenerating payload manifest over the signed runtime binaries"
"$SCRIPT_DIR/lib/regen-payload-manifest.sh" "$RES"
node "$SCRIPT_DIR/lib/payload-manifest.js" verify "$RES" \
  || err_not_released "payload manifest verification failed after regeneration; the payload would fail closed on every target machine."

codesign --force --timestamp --options runtime \
  --entitlements "$SCRIPT_DIR/release/entitlements-gui.plist" \
  --sign "$MACOS_SIGNING_IDENTITY" "$APP_BUNDLE/Contents/MacOS/Portname"
codesign --force --timestamp --options runtime \
  --entitlements "$SCRIPT_DIR/release/entitlements-gui.plist" \
  --sign "$MACOS_SIGNING_IDENTITY" "$APP_BUNDLE"

echo "==> Verifying signature"
codesign --verify --strict --verbose=2 "$APP_BUNDLE"
codesign -d --entitlements - "$APP_BUNDLE" >/dev/null

echo "==> Packing the notarization archive"
# notarytool accepts zip archives, disk images and signed flat packages —
# never an .app directory. The archive is packed from the signed
# bundle BEFORE the submit; the distributable zip is built later from the
# STAPLED bundle.
NOTARY_ZIP="$ROOT/dist/Portname-notarize.zip"
# The interim archive must never survive a failure: a stale
# Portname-notarize.zip could later be mistaken for a release artifact. An
# EXIT trap (not ERR) is required because err_not_released's `exit` and
# commands inside `|| err_not_released` lists do not fire the ERR trap under
# `set -euo pipefail`. On the success path the explicit `rm -f` below has
# already removed the archive and the trap's rm is a no-op.
trap 'rm -f "$NOTARY_ZIP"' EXIT
rm -f "$NOTARY_ZIP"
ditto -c -k --sequesterRsrc --keepParent "$APP_BUNDLE" "$NOTARY_ZIP"
[ -s "$NOTARY_ZIP" ] || err_not_released "notarization archive is missing or empty after packing."

echo "==> Submitting the archive for notarization (waits for Apple's verdict)"
xcrun notarytool submit "$NOTARY_ZIP" \
  --keychain-profile "$NOTARYTOOL_KEYCHAIN_PROFILE" --wait \
  || err_not_released "notarization failed or was rejected; check the notarytool log for the build ID."

echo "==> Stapling the ticket"
xcrun stapler staple "$APP_BUNDLE" \
  || err_not_released "stapling failed; the notarization ticket could not be attached to the app."
xcrun stapler validate "$APP_BUNDLE" \
  || err_not_released "the stapled ticket failed validation; refusing to produce a release artifact."

echo "==> Gatekeeper assessment"
spctl --assess --type execute -vv "$APP_BUNDLE" \
  || err_not_released "Gatekeeper assessment rejected the app; refusing to produce a release artifact."

echo "==> Packing distributable zip from the stapled bundle (preserves signature)"
rm -f "$ZIP"
ditto -c -k --sequesterRsrc --keepParent "$APP_BUNDLE" "$ZIP"
shasum -a 256 "$ZIP"
rm -f "$NOTARY_ZIP"

echo ""
echo "RELEASE artifact ready: $ZIP"
echo "Publishing/uploading remains a deliberate, documented decision (see docs/release-checklist.md)."
